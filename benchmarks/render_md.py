"""Render docs/benchmarks.md from benchmarks/results/<date>/<dataset>/{results,faiss_results}.json.

    python3 benchmarks/render_md.py 2026-10-13 > docs/benchmarks.md
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def load(date, ds, name):
    p = os.path.join(HERE, "results", date, ds, name)
    return json.load(open(p)) if os.path.exists(p) else None


def mb(b):
    return f"{b / 1e6:.1f} MB"


def main(date):
    out = []
    w = out.append
    w("# Benchmarks\n")
    w(f"Generated by `benchmarks/render_md.py {date}` from the JSON files in `benchmarks/results/{date}/`. "
      "Reproduce with:\n")
    w("```bash\ncargo build --release\n./target/release/vdb-bench --out /tmp/lowrank --dataset lowrank\n"
      "./target/release/vdb-bench --out /tmp/mixture --dataset mixture --skip-pq\n"
      "pip install faiss-cpu numpy && python3 benchmarks/faiss_baseline.py /tmp/lowrank   # and /tmp/mixture\n```\n")
    first = load(date, "lowrank", "results.json")
    s = first["setup"]
    w("**Environment.** Single machine: a cloud container with "
      f"{s['cpus']} vCPUs (Intel Xeon @ 2.80 GHz), no GPU. Distance kernel: `{s['kernel']}`. "
      "Other processes were idle during the runs, but this is a shared virtual machine, so expect run-to-run variance of roughly ±10 %. "
      "Numbers are from one run each. They are **not** comparable to published numbers from other hardware.\n")
    w(f"**Setup.** n = {s['n']:,} vectors × {s['dim']} dims, {s['queries']:,} queries from the same distribution (held out), L2, "
      f"HNSW M = {s['m']}, efConstruction = {s['ef_construction']}, k = 10. Recall@10 is measured against exact brute-force search "
      "(top-100 ground truth written to `groundtruth.ivecs`; FAISS is scored against the same file). "
      "The WAL runs with `SyncMode::Never` (no fsync per insert). Latencies are per request through `Collection::search`, "
      "which includes validation, query normalisation and building the result objects.\n")
    w("**Datasets** (deterministic, seed 7):\n")
    w("* `lowrank` (default): a 64-component Gaussian mixture in a 16-d latent space, mapped to 128 dims by a fixed random linear map, plus noise. "
      "It has low intrinsic dimensionality, like real embeddings.")
    w("* `mixture`: a 64-component Gaussian mixture directly in 128 dims. Its high intrinsic dimension makes it a hard case for graph indexes.\n")

    for ds in ["lowrank", "mixture"]:
        r = load(date, ds, "results.json")
        f = load(date, ds, "faiss_results.json")
        if not r:
            continue
        w(f"## Dataset `{ds}`\n")
        b, m = r["build"], r["memory"]
        line = f"Build: {b['seconds']} s ({b['inserts_per_sec']:,.0f} inserts/s, single writer)"
        if f:
            fb = f["build_threads_1"]
            line += f"; FAISS IndexHNSWFlat on 1 thread: {fb['seconds']} s ({fb['inserts_per_sec']:,} inserts/s)"
        w(line + ".\n")
        w(f"Memory: vectors {mb(m['vector_bytes'])}, HNSW graph {mb(m['graph_bytes'])} ({m['graph_bytes_per_vector']} B/vector), "
          f"process RSS {mb(m['rss_bytes'])} after the build. The RSS includes the generated dataset, which is held in memory.\n")
        e = r["exact"]
        w(f"Exact search (brute force, 2 threads): {e['qps']:,.0f} QPS, p50 {e['p50_us']:,.0f} µs.\n")
        w("### Recall and throughput vs ef\n")
        hdr = "| ef | recall@10 | QPS 1 thr | QPS 2 thr | p50 µs | p95 µs | p99 µs |"
        if f:
            hdr += " FAISS recall@10 | FAISS QPS 1 thr (single-query) | FAISS QPS 2 thr (batched) | FAISS p50 µs |"
        w(hdr)
        w("|" + "---|" * (hdr.count("|") - 1))
        fmap = {x["ef"]: x for x in (f or {}).get("hnsw", [])}
        for row in r["hnsw"]:
            t1, t2 = row["threads_1"], row["threads_2"]
            line = (f"| {row['ef']} | {t1['recall_at_10']:.4f} | {t1['qps']:,.0f} | {t2['qps']:,.0f} | "
                    f"{t1['p50_us']:,.0f} | {t1['p95_us']:,.0f} | {t1['p99_us']:,.0f} |")
            if f and row["ef"] in fmap:
                x = fmap[row["ef"]]
                sq = x["threads_1_single_query"]
                line += f" {sq['recall_at_10']:.4f} | {sq['qps']:,} | {x['threads_2_batched']['qps']:,} | {sq['p50_us']:,} |"
            w(line)
        w("")
        w("### Filtered search (ef = 64, 1 thread)\n")
        w("Metadata `bucket = i mod 100`; filter `bucket ≤ b` for the target selectivity. Recall is measured against exact *filtered* search.\n")
        w("| selectivity | plan chosen | recall@10 | QPS | p50 µs | p99 µs |")
        w("|---|---|---|---|---|---|")
        for x in r["filtered_ef64_threads_1"]:
            w(f"| {x['selectivity']} | `{x['plan']}` | {x['recall_at_10']:.4f} | {x['qps']:,.0f} | {x['p50_us']:,.0f} | {x['p99_us']:,.0f} |")
        w("")
        if "pq" in r:
            p = r["pq"]
            w("### Product quantization\n")
            w(f"m = {p['m']} sub-quantizers × {p['ksub']} centroids, trained on {p['train_sample']:,} vectors in {p['train_seconds']} s. "
              f"Codes + codebooks: {mb(p['code_and_codebook_bytes'])} ({p['compression_vs_f32']}× smaller than the f32 vectors). "
              "Search is a full ADC scan followed by an exact rerank of the best `10 × rerank` candidates.\n")
            w("| rerank | recall@10 | QPS | p50 µs | p99 µs |")
            w("|---|---|---|---|---|")
            for x in p["search_threads_1"]:
                w(f"| {x['rerank']} | {x['recall_at_10']:.4f} | {x['qps']:,.0f} | {x['p50_us']:,.0f} | {x['p99_us']:,.0f} |")
            w("")
        d = r["durability"]
        w("### Durability\n")
        w(f"* Snapshot: {mb(d['snapshot_bytes'])} written in {d['snapshot_seconds']} s.")
        w(f"* Recovery from that snapshot: {d['recover_from_snapshot_seconds']} s. Search results were identical before and after recovery.")
        w(f"* Recovery by WAL replay of {d['recover_from_wal_records']:,} inserts (no snapshot): {d['recover_from_wal_seconds']} s. "
          "Replay re-inserts each vector into the graph.\n")

    w("## Reading the results\n")
    w("* On both datasets, the from-scratch HNSW reaches the same recall as FAISS `IndexHNSWFlat` at the same M, efConstruction and efSearch. "
      "Its recall is equal or slightly higher (+0.00 to +0.04), and its single-query throughput is 0.63–1.05× FAISS's (median ≈ 0.7×). FAISS's batched 2-thread numbers are an upper bound "
      "that this engine's request-at-a-time API does not try to match.")
    w("* The build is about 1.3–1.4× slower than FAISS's single-threaded build, and each insert here also encodes and appends a WAL record.")
    w("* Filtered search keeps full recall at every selectivity. At 10 % selectivity, though, HNSW with `ef / selectivity` explores much of the graph "
      "and costs over 10 ms, which is slower than a brute-force scan. The 1 % exact fallback costs about as much again, because metadata is evaluated per slot through a "
      "`BTreeMap`. Both are documented limitations; a columnar metadata index and a cost-based planner are the obvious next steps.")
    w("* PQ compresses the vectors 15× and reaches recall@10 ≥ 0.95 with rerank ≥ 4. Its QPS here is low because the ADC scan is scalar "
      "and is not combined with a coarse quantizer (IVF).")
    w("* The earlier, unpublished run in which the `mixture` set reached only 0.73 recall at ef = 256 had a harness bug: queries came from different cluster centres "
      "than the base set. That bug is fixed; the queries now come from the same draw as the base set.")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
